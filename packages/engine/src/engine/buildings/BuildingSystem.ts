export function getBuildingDef(id: BuildingId): BuildingDefinition {
  return BUILDING_DEFINITIONS[id];
}

export function getBuildingDefById(id: string): BuildingDefinition | undefined {
  return BUILDING_DEFINITIONS[id as BuildingId];
}

/**
 * Retourne les effets d'un type donné pour un bâtiment
 */
export function getBuildingEffects(
  defId: BuildingId,
  effectType: import('../../types/buildings').BuildingEffectType,
): BuildingEffect[] {
  const def = BUILDING_DEFINITIONS[defId];
  if (!def) return [];
  return def.effects.filter((e) => e.type === effectType);
}

/**
 * Maintenance totale de tous les bâtiments actifs d'un joueur
 */
export function calculateBuildingMaintenance(
  buildingIds: string[],
  buildings: Map<string, import('../../types/buildings').BuildingInstance>,
  ownerId: string,
): ResourceBundle {
  const total: ResourceBundle = {};
  for (const bId of buildingIds) {
    const instance = buildings.get(bId);
    if (!instance || instance.ownerId !== ownerId || !instance.isActive) continue;
    const def = BUILDING_DEFINITIONS[instance.definitionId];
    if (!def) continue;
    for (const [res, amount] of Object.entries(def.maintenanceCost) as [
      keyof ResourceBundle,
      number,
    ][]) {
      total[res] = (total[res] ?? 0) + (amount ?? 0);
    }
  }
  return total;
}
